async page => {
 const originalTempo=await page.locator('.bay-music-tempo input').inputValue();
 const receipt=[];const check=(ok,label)=>{if(!ok)throw new Error(label);receipt.push(label)};
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Ивовая арфа',exact:true}).click();
 await page.getByRole('group',{name:'Высота следующей ноты'}).getByRole('button',{name:'Ми',exact:true}).click();
 await page.getByRole('button',{name:'Ивовая арфа, шаг 2: пауза',exact:true}).click();
 check(await page.getByRole('button',{name:'Ивовая арфа, шаг 2: Ми',exact:true}).isVisible(),'note edit selects active track');
 await page.getByRole('button',{name:'Ластик: убирать ноты',exact:true}).filter({visible:true}).click();
 await page.getByRole('button',{name:'Ивовая арфа, шаг 2: Ми',exact:true}).click();
 check(await page.getByRole('button',{name:'Ивовая арфа, шаг 2: пауза',exact:true}).isVisible(),'eraser removes note');
 await page.keyboard.press('Digit8');
 await page.getByRole('button',{name:'Мои мелодии',exact:true}).click();
 await page.getByRole('textbox',{name:'Название мелодии',exact:true}).fill('Вечер в саду');
 await page.getByRole('button',{name:'Сохранить версию',exact:true}).click();
 check((await page.locator('.bay-music-sheet-status').innerText()).includes('сохранена'),'save version feedback inside sheet');
 await page.keyboard.press('Escape');
 check(await page.getByRole('button',{name:'Мои мелодии',exact:true}).evaluate(el=>el===document.activeElement),'Escape restores opener focus');
 await page.getByRole('button',{name:'Настроить звук и дорожки',exact:true}).click();
 await page.getByRole('slider',{name:'Темп мелодии',exact:true}).fill('100');
 await page.getByRole('button',{name:'Очистить выбранную дорожку',exact:true}).click();
 await page.keyboard.press('Escape');
 check((await page.locator('.bay-music-track:not([hidden]) .has-note').count())===0,'clear affects active track');
 await page.getByRole('button',{name:'Мои мелодии',exact:true}).click();
 await page.getByRole('button',{name:'Открыть версию',exact:true}).click();
 await page.keyboard.press('Escape');
 check((await page.locator('.bay-music-track:not([hidden]) .has-note').count())>0,'load restores pattern');
 check((await page.locator('.bay-music-tempo-short').innerText()).includes(originalTempo),'load restores tempo');
 await page.getByRole('button',{name:'Выключить звук: Ивовая арфа',exact:true}).click();
 check(await page.locator('.bay-music-track:not([hidden])').evaluate(el=>el.classList.contains('is-muted')),'mute active track');
 await page.getByRole('button',{name:'Включить звук: Ивовая арфа',exact:true}).click();
 await page.getByRole('button',{name:'Глиняный барабан',exact:true}).click();
 await page.getByRole('button',{name:'Настроить звук и дорожки',exact:true}).click();
 await page.getByRole('button',{name:'Очистить выбранную дорожку',exact:true}).click();
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Ивовая арфа',exact:true}).click();
 await page.getByRole('button',{name:'▶ Играть',exact:true}).click();
 await page.locator('.bay-music-play[aria-pressed=true]').waitFor();
 await page.locator('.bay-music-track:not([hidden]) .is-current').first().waitFor();
 check(true,'sample engine starts and transport advances');
 if(await page.getByRole('button',{name:'Записывать касания инструментов',exact:true}).getAttribute('aria-pressed')!=='true') await page.getByRole('button',{name:'Записывать касания инструментов',exact:true}).click();
 const cdp=await page.context().newCDPSession(page);await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true});
 await page.evaluate(()=>{window.musicTouches=0;document.querySelector('.bay-music').addEventListener('pointerdown',e=>{if(e.pointerType==='touch')window.musicTouches++})});
 const instrument=await page.getByRole('button',{name:'Глиняный барабан',exact:true}).boundingBox();
 const point={x:instrument.x+instrument.width/2,y:instrument.y+instrument.height/2};
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[point]});await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 check(await page.evaluate(()=>window.musicTouches)>0,'native touch selects and plays instrument');
 check((await page.locator('.bay-music-track:not([hidden]) h2').innerText())==='Глиняный барабан','touch updates composer selection');
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('cozy-farm-island-v1')).musicGarden.tracks.ceramic.steps.some(note=>note===7));
 check(true,'native touch recorded into saved active pattern');
 await page.getByRole('button',{name:'Ⅱ Пауза',exact:true}).click();
 check(!(await page.locator('.bay-music').evaluate(el=>el.classList.contains('is-playing'))),'stop transport');
 await cdp.detach();
 await page.getByRole('button',{name:'Погремушки из семян. Нужны материалы из других островов',exact:true}).click();
 check((await page.locator('.bay-music-materials').innerText()).includes('Родной остров'),'locked instrument reveals real material source');
 check(await page.getByRole('button',{name:'Собрать инструмент',exact:true}).isDisabled(),'insufficient materials cannot be consumed');
 await page.screenshot({path:'output/playwright/music-materials-390.png'});
 return receipt;
}
